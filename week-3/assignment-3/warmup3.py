# not True becomes False
# False is False
print(not True and False) 

# False and False is False
# True or False is True
print(True or False and False) 

# Phyton follows order: not, and, or
# or only need a condition to be True

# 5 > 3 is True; not True becomes False
print(not (5 > 3))

# First True, second False, so the result is False
# == means equal 
# != means not equal to
# and requires both comparisons to be True.
print(10 == 10 and 4 != 4)

# not False is True
# not True is False
# True or False is True
print(not False or not True)  